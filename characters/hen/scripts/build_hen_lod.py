if sum_before>BUDGET:
    print("REBALANCE",sum_before,"must be <=",BUDGET,"body",tri_count(body),"=>",reserve,flush=True)
    assert reserve>200,(BUDGET,other)
    mod=body.modifiers.new("Fit body to global budget","DECIMATE")
    mod.ratio=max(.02,min(.98,reserve/tri_count(body)))
    bpy.context.view_layer.objects.active=body
    bpy.ops.object.modifier_apply(modifier=mod.name)
