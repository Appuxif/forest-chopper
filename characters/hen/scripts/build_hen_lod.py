def new_mat(name,color,rough=.8):
    m=bpy.data.materials.new(name)
    m.diffuse_color=(*color,1)
    m.use_nodes=True
    pr=m.node_tree.nodes.get("Principled BSDF")
    pr.inputs["Base Color"].default_value=(*color,1)
    pr.inputs["Roughness"].default_value=rough
    return m

image=bpy.data.images.load(str(ATLAS),check_existing=True)
image.pack()
feather=new_mat("Hen Plumage | color atlas",(1,1,1),.88)
nd=feather.node_tree.nodes
tex=nd.new("ShaderNodeTexImage")
tex.name="Recolorable Feather Atlas"
tex.image=image
tex.extension="CLIP"
feather.node_tree.links.new(tex.outputs["Color"],nd.get("Principled BSDF").inputs["Base Color"])
feather.use_backface_culling=False
static_mat["plumage"]=feather
static_mat["leg"]=new_mat("Feet • ochre",(0.58,.34,.09),.86)
