N_TAIL=11 if BUDGET==10000 else 7
for s in (-1,1):
    for i in range(N_WING):
        t=i/max(1,N_WING-1)
        a=(s*(.488+.016*math.sin(t*math.pi)),-.35+t*.68,1.145-.145*t)
        b=(s*(.53+.01*t),-.12+t*.72,1.04-.13*t)
        feather_ribbon("Wing primary",a,b,(0,.40,.92),.041,
                       3 if BUDGET==10000 else 2,"wing")
for i in range(N_TAIL):
    t=(i-(N_TAIL-1)/2)/((N_TAIL-1)/2)
    a=(t*.10,.81,1.34)
    b=(t*.30,1.25+.09*(1-abs(t)),1.65-.12*abs(t))
    feather_ribbon("Tail flight feather",a,b,(1,0,0),.066,
                   4 if BUDGET==10000 else 3,"tail")

# Accurate triangle limit: reduce only body again, don't destroy face/leg detail.
