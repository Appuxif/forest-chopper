def tri_count(ob):
    return sum(max(0,len(poly.vertices)-2) for poly in ob.data.polygons)
def assign(ob,material):
    ob.data.materials.clear()
    ob.data.materials.append(material)
def reduce_obj(src,limit,mat,role):
    copy=src.copy();copy.data=src.data.copy()
    model_col.objects.link(copy)
    copy.name="LOD "+TAG+" | "+src.name
    copy.animation_data_clear()
    # Upper thighs were present in the source, but earlier LOD builds excluded them.
    # Feathered drumsticks overlap belly and meet the upper tarsus; keep plumage
    # and use identical recolorable UVs as the torso instead of a leg-color patch.
    if role == "thigh":
        # Feathered upper thigh is largely hidden inside the body.
        # Shift the tapered underside towards the shin rather than leaving
        # a free-floating sphere below the plumage silhouette.
        side = -1 if copy.location.x < 0 else 1
        for v in copy.data.vertices:
            t = max(0.,min(1.,(v.co.z + .145)/.29))
            taper = .66 + .52*t
            v.co.x = v.co.x * 1.37*taper + side*.032*(1-t)
            v.co.y = v.co.y * 1.10*taper + .026*(1-t)
            v.co.z = v.co.z * 1.06
        copy.location.z += .005
    assign(copy,mat)
    original=tri_count(copy)
    if original>limit+3:
        mod=copy.modifiers.new("Triangle budget","DECIMATE")
        mod.decimate_type='COLLAPSE'
        mod.ratio=max(.001,min(.99,limit/original))
        bpy.context.view_layer.objects.active=copy
        bpy.ops.object.modifier_apply(modifier=mod.name)
    if mat==feather:
        unwrap_plumage(copy,role)
    for p in copy.data.polygons:p.use_smooth=True
    print(role,src.name,original,'->',tri_count(copy),flush=True)
    return copy

def unwrap_plumage(ob,role):
    mesh=ob.data
    uv=mesh.uv_layers.get("UVMap") or mesh.uv_layers.new(name="UVMap")
    M=ob.matrix_world
    normals=M.to_3x3()
    for poly in mesh.polygons:
        n=(normals@poly.normal).normalized()
        for li in poly.loop_indices:
            co=M @ mesh.vertices[mesh.loops[li].vertex_index].co
            x,y,z=co.x,co.y,co.z
            if role=="tail":
                u=.82+max(0,min(.17,(x+.32)/.70*.17))
                v=max(.003,min(.99,(z-1.20)/.62))
            elif role=="wing":
                # V increases along the wing feathers and follows shingle direction.
                u=.025+.74*max(.0,min(1.,(z-.88)/.55))
                v=max(.003,min(.995,(y+.54)/1.50))
            else: # body/head: orthographic-per-face UV projection
                if abs(n.y)>max(abs(n.x),abs(n.z))*.82:
                    u=.02+max(0,min(1,(x+.57)/1.14))*.75
                    v=max(.0,min(.99,(z-.47)/1.46))
                elif abs(n.x)>abs(n.z)*.85:
                    u=.02+max(0,min(1,(y+1.0)/2.0))*.75
                    v=max(.0,min(.99,(z-.47)/1.46))
                else:
                    u=.02+max(0,min(1,(x+.57)/1.14))*.75
                    v=max(.0,min(.99,(y+.99)/1.94))
            uv.data[li].uv=(u,v)

def classify(o):
    n=o.name
    if n.startswith("HEN •"):return "body"
    if n.startswith("Feathery thigh"):return "thigh"
    if n.startswith(("L • wing","R • wing")):return "wing"
    if n.startswith("Tarsometatarsus"):return "shank"
    if n.startswith("Front toe"):return "toe"
    if n.startswith("Front claw"):return "claw"
    if n.startswith("Hallux"):return "hallux"
    if n.startswith("Rear claw"):return "rearclaw"
    if n.startswith("Upper beak"):return "beak"
    if n.startswith("Lower beak"):return "beaklower"
    if n.startswith(("Wet black eye","Dark pupil")):return "eye"
    if n.startswith("Amber iris"):return "iris"
    if n.startswith("Eye socket"):return "socket"
    if n.startswith("Naris"):return "nostril"
    if n.startswith("Earlobe"):return "earlobe"
    if n.startswith("Fleshy wattle"):return "wattle"
    if n.startswith("Wattle tip"):return "wattletip"
    if n.startswith("Single upright"):return "comb"
    return None

mat_for={
 "body":"plumage","thigh":"plumage","wing":"plumage",
 "shank":"leg","toe":"leg","claw":"claw","hallux":"leg","rearclaw":"claw",
 "beak":"beak","beaklower":"beaklower","eye":"eye","iris":"iris",
 "socket":"socket","nostril":"nostril","earlobe":"comb",
 "wattle":"comb","wattletip":"comb","comb":"comb"
}
body=None
retained=[]
for o in sources:
    tag=classify(o)
    if tag is None: continue
    max_tris=targets.get(tag)
    # shared simplification budgets for the four concentric eye elements
    if tag in ("iris","socket"):max_tris=targets["eye"]
    if tag=="earlobe":max_tris=targets["earlobe"]
    if tag=="wattletip":max_tris=targets["wattletip"]
    if tag=="comb":max_tris=targets["comb"]
    co=reduce_obj(o,max_tris,static_mat[mat_for[tag]],
                  "wing" if tag=="wing" else "body" if tag=="body" else tag)
    retained.append(co)
    if tag=="body":body=co
assert body is not None

# Ribbon feathers on the wing edges and fan-shaped tail: minor silhouette detail.
def feather_ribbon(name,a,b,side,width,segments,uv_role,bend=.018):
    a,b,side=Vector(a),Vector(b),Vector(side).normalized()
    verts=[];faces=[]
    for i in range(segments+1):
        t=i/segments
        center=a.lerp(b,t)+Vector((0,0,1))*bend*math.sin(math.pi*t)
        w=width*(math.sin(math.pi*(.04+.94*t))**.72)*(1-.1*t)
        for signed in (-1,0,1):
            verts.append(tuple(center+side*(w*signed)+Vector((0,0,1))*(1-abs(signed))*.012))
    for i in range(segments):
        j=i*3
        faces.extend([(j,j+1,j+4,j+3),(j+1,j+2,j+5,j+4)])
    mesh=bpy.data.meshes.new(name)
    mesh.from_pydata(verts,[],faces);mesh.update()
    o=bpy.data.objects.new(name,mesh);model_col.objects.link(o)
    assign(o,feather)
    unwrap_plumage(o,uv_role)
    for poly in o.data.polygons:poly.use_smooth=True
    retained.append(o)

# Shape visible primaries without high-density individual feather mesh.
